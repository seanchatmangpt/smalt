"""`smalt-migrate inject` / `rollback` — loopback .env.smalt emission (REQ-3.1).

Reads the topology IR produced by `smalt_cli.migrate.scan` (schema
``smalt-migrate/topology-v1``) and renders a .env.smalt with loopback
connection strings per discovered service:

    cosmos       AccountEndpoint=http://127.0.0.1:8443;AccountKey=<emulator key>
    blob         DefaultEndpointsProtocol=http;...;BlobEndpoint=http://127.0.0.1:8443/<acct>
    servicebus   Endpoint=sb://127.0.0.1:5672;SharedAccessKeyName=...;SharedAccessKey=<dev key>
    keyvault     http://127.0.0.1:8443 (AZURE_KEYVAULT_VAULTURI)

NFR-1: read-only by construction — no network/cloud calls anywhere in this
module; the only I/O is the .env.smalt write (and its .bak backup).

Behavior:
    inject    backs up an existing target to <target>.bak, then writes.
    rollback  restores <target>.bak over the injected file; with no .bak
              present it removes the injected file (nothing persisted
              survives). With neither present it is a no-op.
    --dry-run prints the rendered body without touching the filesystem.
"""

from __future__ import annotations

import base64
import hashlib
import json
import shutil
from pathlib import Path
from typing import Any

import typer

from .scan import migrate_app

# Canonical Azure Cosmos emulator key (accepted by smalt's cosmos surface in
# test mode, same value the real Cosmos emulator ships with).
COSMOS_EMULATOR_KEY = (
    "C2y6yDjf5/R+ob0N8A7Cgv30VRDDIWEHLM+4QDU5DE2nQ9nDuVTqobD4b8mGGyPMbIZnqyMsEcaGQy67XIw/Jw=="
)

# Per-host dev key from scripts/dev_env.sh: base64(sha256(host + "smalt-dev-sb")).
DEV_KEY_SUFFIX = "smalt-dev-sb"

LOOPBACK_HOST = "127.0.0.1"
EGRESS_PORT = 8443
SB_PORT = 5672
EH_PORT = 5673
ARM_PORT = 9443

ENV_HEADER = "# .env.smalt — generated by smalt-migrate inject (REQ-3.1). Loopback only."


def dev_key(host: str = LOOPBACK_HOST) -> str:
    """base64(sha256(host + "smalt-dev-sb")) — the dev_env.sh shared-key scheme."""
    digest = hashlib.sha256((host + DEV_KEY_SUFFIX).encode()).digest()
    return base64.b64encode(digest).decode()


def discovered_services(topology: dict[str, Any]) -> set[str]:
    """Map topology IR sections to the service set present in the scan.

    Pure function over the topology dict. An empty/absent topology yields the
    default full surface (cosmos, blob, servicebus, keyvault) so a bare
    ``inject`` still produces a working loopback env.
    """
    if not isinstance(topology, dict) or not topology:
        return {"cosmos", "blob", "servicebus", "keyvault"}
    services: set[str] = set()
    if topology.get("cosmos_databases"):
        services.add("cosmos")
    if topology.get("object_storage"):
        services.add("blob")
    for ns in topology.get("messaging_namespaces") or []:
        kind = ns.get("kind") if isinstance(ns, dict) else None
        if kind == "servicebus":
            services.add("servicebus")
        elif kind == "eventhub":
            services.add("eventhubs")
    if topology.get("security_vaults"):
        services.add("keyvault")
    return services or {"cosmos", "blob", "servicebus", "keyvault"}


def _account_name(topology: dict[str, Any], default: str = "smaltacct") -> str:
    for c in topology.get("object_storage") or []:
        if isinstance(c, dict) and isinstance(c.get("storage_account_ref"), dict):
            raw = c["storage_account_ref"].get("raw")
            if isinstance(raw, str):
                return raw
        if isinstance(c, dict) and isinstance(c.get("storage_account_ref"), str):
            return c["storage_account_ref"]
    return default


def render_env(
    services: set[str],
    host: str = LOOPBACK_HOST,
    account: str = "smaltacct",
    header: str = ENV_HEADER,
) -> str:
    """Render the .env.smalt body for the given service set (pure, no I/O)."""
    lines: list[str] = [header, ""]
    if "cosmos" in services:
        lines.append(
            f"SMALT_COSMOS_CONNECTION_STRING="
            f"AccountEndpoint=http://{host}:{EGRESS_PORT};AccountKey={COSMOS_EMULATOR_KEY}"
        )
    if "blob" in services:
        lines.append(
            f"AZURE_STORAGE_CONNECTION_STRING="
            f"DefaultEndpointsProtocol=http;AccountName={account};"
            f"AccountKey={dev_key(host)};"
            f"BlobEndpoint=http://{host}:{EGRESS_PORT}/{account};"
            f"QueueEndpoint=http://{host}:{EGRESS_PORT}/{account}/queue;"
            f"TableEndpoint=http://{host}:{EGRESS_PORT}/{account}/table"
        )
    if "servicebus" in services:
        lines.append(
            f"SMALT_SERVICEBUS_CONNECTION_STRING="
            f"Endpoint=sb://{host}:{SB_PORT};"
            f"SharedAccessKeyName=RootManageSharedAccessKey;"
            f"SharedAccessKey={dev_key(host)}"
        )
    if "eventhubs" in services:
        lines.append(
            f"SMALT_EVENTHUBS_CONNECTION_STRING="
            f"Endpoint=sb://{host}:{EH_PORT};"
            f"SharedAccessKeyName=RootManageSharedAccessKey;"
            f"SharedAccessKey={dev_key(host)}"
        )
    if "keyvault" in services:
        lines.append(f"AZURE_KEYVAULT_VAULTURI=http://{host}:{EGRESS_PORT}")
    lines.append(f"SMALT_ARM_ENDPOINT=https://{host}:{ARM_PORT}")
    lines.append(f"AZURE_ARM_ENDPOINT=https://{host}:{ARM_PORT}")
    return "\n".join(lines) + "\n"


def build_env(topology: dict[str, Any], host: str = LOOPBACK_HOST) -> str:
    """Convenience: discover services from a topology dict, then render."""
    return render_env(
        discovered_services(topology),
        host=host,
        account=_account_name(topology),
    )


def _load_topology(path: str | None) -> dict[str, Any]:
    if not path:
        return {}
    raw = Path(path).read_text(encoding="utf-8")
    topo = json.loads(raw)
    if not isinstance(topo, dict):
        raise typer.BadParameter(f"topology {path} is not a JSON object")
    return topo


def _backup_path(target: Path) -> Path:
    return target.with_name(target.name + ".bak")


@migrate_app.command("inject")
def inject(
    topology: str = typer.Option(
        None, "--topology", "-t", help="Topology JSON from `smalt-migrate scan`."
    ),
    target: Path = typer.Option(
        Path(".env.smalt"), "--target", help="Env file to write (default .env.smalt)."
    ),
    dry_run: bool = typer.Option(False, "--dry-run", help="Print without writing."),
) -> None:
    """Emit .env.smalt with loopback connection strings per discovered service."""
    body = build_env(_load_topology(topology))
    if dry_run:
        typer.echo(body, nl=False)
        typer.echo(f"[dry-run] no file written at {target}", err=True)
        return
    target = Path(target)
    if target.exists():
        backup = _backup_path(target)
        shutil.copy2(target, backup)
        typer.echo(f"backup: {target} -> {backup}")
    target.write_text(body, encoding="utf-8")
    typer.echo(f"injected: {target} ({len(body.splitlines())} lines)")


@migrate_app.command("rollback")
def rollback(
    target: Path = typer.Option(
        Path(".env.smalt"), "--target", help="Env file to roll back (default .env.smalt)."
    ),
) -> None:
    """Restore the .bak over the injected file; without a .bak, remove the injection."""
    target = Path(target)
    backup = _backup_path(target)
    if backup.exists():
        shutil.copy2(backup, target)
        typer.echo(f"rollback: restored {target} from {backup}")
        return
    if target.exists():
        target.unlink()
        typer.echo(f"rollback: removed injected {target} (no .bak present)")
        return
    typer.echo(f"rollback: nothing to do ({target} and {backup} both absent)")
