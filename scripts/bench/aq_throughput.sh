#!/usr/bin/env bash
# scripts/bench/aq_throughput.sh — lane L46: first AoQ bench lane.
#
# Exercises the AoQ listener -> pool -> worker path end to end:
#   boot the AoQ plane (SMALT_PLANES=aoq; the az_prod_aoq profile flips
#   config :smalt, :aoq, enabled: true; the DataSupervisor mounts
#   Smalt.Aoq.Supervisor = NifHolder -> WorkerPool -> Listener), then push
#   N frames through the UDP listener (encoded via Smalt.Aoq.Frame.encode_frame
#   — 64B header + >=1B body framing law) and measure frames/sec end to end
#   (send -> pool seq atomics -> worker-m mailbox drain, real observables
#   only) plus the iolist-egress alloc delta (encode_frame iolist vs a
#   flat-binary concat baseline, GC-bounded process-memory delta, bytes/frame).
#
# Port law: lane L46 -> 39460..39465 (39000 + 10*46). AoQ listener pinned to
# +5 (39465) via config override (collision law: the shared substrate may
# hold 9093); the data-plane boot's other listeners stay on the MIX_ENV=test
# probed-free ports (config/test.exs).
#
# Not a load harness: one lane, bounded rounds (default 5), min-of-N headline
# (ratio-fence law). No sleeps as coordination: every wait is a bounded poll
# on a real observable (listener local_port/0, pool seq atomics, worker
# mailbox drain, run-completed metrics file).
#
# Run: ./scripts/bench/aq_throughput.sh            (env: L46_N, L46_ROUNDS)
# Result: tmp/aq-throughput.jsonl (bench_emit shape), boot log tmp/l46-aoq-boot.log
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
source "$REPO/scripts/bench/lib.sh"

# Pinned toolchain per .tool-versions (elixir 1.20.4-otp-29, erlang 29.1.2) —
# mirrors justfile.d/58-posh.just's PATH pin; the ambient elixir (1.19.5) is
# below the mix.exs requirement.
export PATH="$HOME/.asdf/installs/erlang/29.1.2/bin:$HOME/.asdf/installs/elixir/1.20.4-otp-29/bin:$PATH"

BENCH_LANE="l46"
BENCH_RESULTS_DIR="$REPO/tmp"
RESULT_FILE="$BENCH_RESULTS_DIR/aq-throughput.jsonl"
LOG="$REPO/tmp/l46-aoq-boot.log"
EXS="$REPO/tmp/l46_bench.exs"
METRICS="$REPO/tmp/l46-metrics.txt"
LANE_ROOT="$REPO/_build-lane-l46"

# Lane L46 block: 39000 + 10*46 .. +5. AoQ listener on +5.
LANE_BASE=39460
EGRESS=$((LANE_BASE + 1))
AOQ=$((LANE_BASE + 5))

# -- Pre-flight: the ports this lane touches must be free ---------------------
for p in "$EGRESS" "$AOQ"; do
  if lsof -nP -iTCP:"$p" -sTCP:LISTEN >/dev/null 2>&1 || lsof -nP -iUDP:"$p" >/dev/null 2>&1; then
    echo "[l46] port $p already held — refusing to boot (collision)" >&2
    exit 1
  fi
done

mkdir -p "$BENCH_RESULTS_DIR"
: >"$RESULT_FILE"
rm -f "$METRICS"

# -- The bench (single beam: boot + measure + halt) ---------------------------
cat >"$EXS" <<'EXS'
# tmp/l46_bench.exs — generated by scripts/bench/aq_throughput.sh (lane L46).
# Boots the app with SMALT_PLANES=aoq, benches the AoQ path, writes
# tmp/l46-metrics.txt, halts. Bash emits the jsonl via bench_emit.

defmodule SmaltBench.L46 do
  @payload :binary.copy(<<0xAB>>, 512)

  # Bounded poll on a real observable. The per-iteration wait is a
  # `receive after 2` POLL-STEP (SLEEP-CLASS: POLL-STEP — the runtime
  # schedules the process away for 2ms between checks; never a fixed
  # sleep-as-coordination), deadline-checked with a typed timeout.
  def wait_until(fun, ms) do
    deadline = System.monotonic_time(:millisecond) + ms
    go = fn go ->
      case fun.() do
        {:ok, v} -> v
        _ ->
          if System.monotonic_time(:millisecond) >= deadline do
            raise("TYPED-TIMEOUT(wait_until #{ms}ms)")
          else
            receive do
            after
              2 -> go.(go)
            end
          end
      end
    end
    go.(go)
  end

  def dispatch, do: :persistent_term.get({Smalt.Aoq.WorkerPool, :dispatch})

  def drained? do
    {c, _d, _s} = dispatch()
    Enum.all?(0..(c - 1), fn i ->
      pid = Process.whereis(Smalt.Aoq.Worker.registered(i))
      pid != nil and elem(:erlang.process_info(pid, :message_queue_len), 1) == 0
    end)
  end

  def frame(seq) do
    {:ok, iol} =
      Smalt.Aoq.Frame.encode_frame(
        %Smalt.Aoq.Frame{epoch: 0, seq: seq, type: 0x01, flags: 0, payload_len: byte_size(@payload)},
        @payload
      )
    iol
  end

  def encode_frame do
    {:ok, iol} =
      Smalt.Aoq.Frame.encode_frame(
        %Smalt.Aoq.Frame{epoch: 0, seq: 0, type: 0x01, flags: 0, payload_len: byte_size(@payload)},
        @payload
      )
    iol
  end

  # -- Op 1: end-to-end ingest (UDP send -> listener -> pool -> worker parse)
  def ingest_round(sock, port, n) do
    {c, _d, seq} = dispatch()
    start = :atomics.get(seq, 1)
    target = start + n
    frame = frame(start)
    :erlang.garbage_collect()
    t0 = System.monotonic_time(:native)
    for _ <- 1..n, do: :ok = :gen_udp.send(sock, {127, 0, 0, 1}, port, frame)
    # Bounded drain poll: pool seq atomics reached target AND every worker
    # mailbox empty — real observables, never a clock.
    delta_ns =
      wait_until(
        fn ->
          if :atomics.get(seq, 1) >= target and drained?(), do: {:ok, System.monotonic_time(:native) - t0}, else: :retry
        end,
        120_000
      )
    elapsed_s = delta_ns / 1.0e9
    {start, n / max(elapsed_s, 1.0e-9), elapsed_s}
  end

  # -- Op 2: iolist-egress alloc delta (GC-bounded process-memory bytes/frame)
  # Runs in a dedicated process so the measurement window is its whole heap.
  def alloc_probe(n) do
    parent = self()
    pid =
      spawn(fn ->
        iol = encode_frame()
        flat = IO.iodata_to_binary(iol)

        # iolist egress (the deployed encode_frame shape)
        :erlang.garbage_collect()
        m0 = elem(:erlang.process_info(self(), :memory), 1)
        lats =
          for _ <- 1..n do
            s = System.monotonic_time(:native)
            _ = encode_frame()
            System.monotonic_time(:native) - s
          end
        :erlang.garbage_collect()
        m1 = elem(:erlang.process_info(self(), :memory), 1)
        alloc_iol = m1 - m0

        # flat-binary concat baseline (the banned egress shape, for delta)
        :erlang.garbage_collect()
        f0 = elem(:erlang.process_info(self(), :memory), 1)
        for _ <- 1..n, do: <<0::unsigned-integer-size(512), 0::size(0)>> <> flat
        :erlang.garbage_collect()
        f1 = elem(:erlang.process_info(self(), :memory), 1)
        alloc_flat = f1 - f0

        send(parent, {:l46_alloc, alloc_iol, alloc_flat, lats})
      end)

    receive do
      {:l46_alloc, alloc_iol, alloc_flat, lats} ->
        bpf_iol = alloc_iol / n
        bpf_flat = alloc_flat / n
        sorted = Enum.sort(lats)
        nth = fn p ->
          idx = max(0, min(length(sorted) - 1, ceil(p / 100 * length(sorted)) - 1))
          Enum.at(sorted, idx) / 1_000_000.0
        end
        mean_ns = Enum.sum(lats) / length(lats)
        %{iol_bpf: bpf_iol, flat_bpf: bpf_flat, delta_bpf: bpf_iol - bpf_flat,
          enc_ops_s: 1.0e9 / mean_ns,
          p50: nth.(50), p95: nth.(95), p99: nth.(99)}
    after
      120_000 -> raise "TYPED-TIMEOUT(alloc probe)"
    end
  end
end

frames = String.to_integer(System.get_env("L46_N") || "20000")
rounds = String.to_integer(System.get_env("L46_ROUNDS") || "5")
Application.put_env(:smalt, :aoq, enabled: true, port: String.to_integer(System.get_env("L46_AOQ_PORT")))
Application.put_env(:smalt, :egress_port, String.to_integer(System.get_env("L46_EGRESS_PORT")))
{:ok, _} = Application.ensure_all_started(:smalt)

# Readiness: the listener's local_port/0 observable (nil before bind).
port =
  SmaltBench.L46.wait_until(
    fn ->
      case Smalt.Aoq.Listener.local_port() do
        p when is_integer(p) -> {:ok, p}
        _ -> :retry
      end
    end,
    90_000
  )

# Sanity: plane structurally up (pool worker census, never a clock).
{count, _dispatch, _seq} = SmaltBench.L46.dispatch()
true = count > 0 and Smalt.Aoq.WorkerPool.live_workers() == count

{:ok, sock} = :gen_udp.open(0, [:binary, active: false])

round_results = Enum.map(:lists.seq(1, rounds), fn _r -> SmaltBench.L46.ingest_round(sock, port, frames) end)
fps = Enum.map(round_results, &elem(&1, 1))
min_fps = Enum.min(fps)
avg_fps = Enum.sum(fps) / length(fps)

alloc = SmaltBench.L46.alloc_probe(frames)
iol = SmaltBench.L46.encode_frame()
frame_bytes = IO.iodata_to_binary(iol) |> byte_size()

lines = [
  "rounds #{rounds} n #{frames} payload 512B frame #{frame_bytes}B workers #{count}",
  "ingest_fps " <>
    Enum.join(Enum.map(round_results, fn {s, f, e} -> "seq#{s}:#{Float.round(f, 1)}fps(#{Float.round(e, 3)}s)" end), " "),
  "ingest_min_fps #{Float.round(min_fps, 1)}",
  "ingest_avg_fps #{Float.round(avg_fps, 1)}",
  "alloc_iolist_bytes_per_frame #{Float.round(alloc.iol_bpf, 2)}",
  "alloc_flat_bytes_per_frame #{Float.round(alloc.flat_bpf, 2)}",
  "alloc_delta_bytes_per_frame #{Float.round(alloc.delta_bpf, 2)}",
  "encode_ops_per_sec #{Float.round(alloc.enc_ops_s, 1)}",
  "encode_p50_ms #{Float.round(alloc.p50, 4)}",
  "encode_p95_ms #{Float.round(alloc.p95, 4)}",
  "encode_p99_ms #{Float.round(alloc.p99, 4)}"
]

File.write!("/Users/sac/smalt/tmp/l46-metrics.txt", Enum.join(lines, "\n") <> "\n")
:ok = :gen_udp.close(sock)
IO.puts(:stderr, "[l46] done: min #{Float.round(min_fps, 1)} fps, alloc iol #{Float.round(alloc.iol_bpf, 2)} B/frame")
System.halt(0)
EXS

# -- Boot + run (one beam), bounded poll on the metrics file ------------------
echo "[l46] booting AoQ plane (planes=aoq, aoq listener $AOQ, egress $EGRESS), N=${L46_N:-20000} x${L46_ROUNDS:-5} rounds..." >&2
MIX_ENV=test \
MIX_BUILD_ROOT="$LANE_ROOT" \
SMALT_PLANES=aoq \
L46_AOQ_PORT="$AOQ" L46_EGRESS_PORT="$EGRESS" L46_N="${L46_N:-20000}" L46_ROUNDS="${L46_ROUNDS:-5}" \
mix run "$EXS" >"$LOG" 2>&1 </dev/null 9>&- &
BENCH_BOOT_PID=$!
trap 'bench_down "${BENCH_BOOT_PID:-}"' EXIT INT TERM

rc=1
for i in $(seq 1 300); do
  if [ -s "$METRICS" ]; then rc=0; break; fi
  kill -0 "$BENCH_BOOT_PID" 2>/dev/null || break
  sleep 1 # SLEEP-CLASS: POLL-STEP — bounded poll on a real observable
done

if [ "$rc" -ne 0 ]; then
  echo "[l46] BLOCKED(aoq-boot): beam pid $BENCH_BOOT_PID died early or produced no metrics within 300s; log: $LOG" >&2
  tail -30 "$LOG" >&2 || true
  exit 3
fi

# -- Parse metrics + emit via bench_emit (receipt-cited counts re-read) -------
FPS_MIN=$(grep '^ingest_min_fps' "$METRICS" | awk '{print $2}')
FPS_AVG=$(grep '^ingest_avg_fps' "$METRICS" | awk '{print $2}')
ROUND_LINE=$(grep '^ingest_fps ' "$METRICS" | cut -d' ' -f2-)
N_VAL=$(grep '^rounds ' "$METRICS" | awk '{print $4}')
ALLOC_DELTA=$(grep '^alloc_delta_bytes_per_frame' "$METRICS" | awk '{print $2}')

echo "[l46] measured: min $FPS_MIN frames/s, avg $FPS_AVG frames/s | rounds: $ROUND_LINE | alloc delta $ALLOC_DELTA B/frame" >&2

# Headline record: min-of-N (ratio-fence law). Per-round windows carry no
# per-frame latency sample — the fps fields carry the claim; per-frame
# percentiles ride the encode op record.
bench_emit "$RESULT_FILE" "aoq-plane" "udp_ingest_drain_min" "$N_VAL" "$FPS_MIN" 0.0 0.0 0.0 0
bench_emit "$RESULT_FILE" "aoq-plane" "udp_ingest_drain_avg" "$N_VAL" "$FPS_AVG" 0.0 0.0 0.0 0
ENC_OPS=$(grep '^encode_ops_per_sec' "$METRICS" | awk '{print $2}')
P50=$(grep '^encode_p50_ms' "$METRICS" | awk '{print $2}')
P95=$(grep '^encode_p95_ms' "$METRICS" | awk '{print $2}')
P99=$(grep '^encode_p99_ms' "$METRICS" | awk '{print $2}')
bench_emit "$RESULT_FILE" "aoq-plane" "iolist_encode" "$N_VAL" "$ENC_OPS" "$P50" "$P95" "$P99" 0
bench_emit "$RESULT_FILE" "aoq-plane" "iolist_egress_alloc_bpf" "$N_VAL" "$ALLOC_DELTA" 0.0 0.0 0.0 0

echo "[l46] results: $RESULT_FILE" >&2
