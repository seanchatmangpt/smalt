FALLBACK_MEANING = "Error emitted by the substrate; see the cited source for the exact message template."
FALLBACK_REMEDIATION = "Read the message body; fix the request per the cited source."


def line_of(text, pos):
    return text.count("\n", 0, pos) + 1


def annotate(code):
    meaning, remediation = ANNOTATIONS.get(code, (FALLBACK_MEANING, FALLBACK_REMEDIATION))
    marked = code in ANNOTATIONS
    return meaning, remediation, marked


def esc(s):
    # Backslash FIRST, then pipe: a source literal backslash must become
    # `\\` so the doc round-trips (lens 5: `a\|b` previously projected as
    # `a\\|b`, which every escape-aware parser read back as `a|b` — the
    # backslash was silently dropped).
    return s.replace("\\", "\\\\").replace("|", "\\|").replace("\n", " ")


def extract_arm():
    rows = []
    src = ARM.read_text()
    # A) send_arm_error(conn, STATUS, "Code", ...)
    for m in re.finditer(r'send_arm_error\(\s*conn,\s*(\d+),\s*"([A-Za-z][A-Za-z0-9]*)"', src, re.S):
        status, code = int(m.group(1)), m.group(2)
        rows.append((status, code, f"{ARM.relative_to(ROOT)}:{line_of(src, m.start())}"))
    # B) pinned GraphLaw refusal: InvalidResourceShape @ 400, target AshGraphLaw.Enforcement
    if 'send_graphlaw_refusal' in src:
        line = line_of(src, src.index("defp send_graphlaw_refusal"))
        rows.append((400, "InvalidResourceShape", f"{ARM.relative_to(ROOT)}:{line}"))
    # C) inline 412 PreconditionFailed envelope (NOT via send_arm_error - pinned set)
    for m in re.finditer(r'send_json\(conn,\s*412,\s*body\)', src):
        # find the nearest preceding "code" => literal above the send site
        window = src[max(0, m.start() - 1500):m.start()]
        codes = re.findall(r'"code"\s*=>\s*"([A-Za-z][A-Za-z0-9]*)"', window)
        if codes:
            rows.append((412, codes[-1], f"{ARM.relative_to(ROOT)}:{line_of(src, m.start())}"))
    # dedupe by (status, code), keep first source cite
    seen = {}
    for status, code, cite in rows:
        seen.setdefault((status, code), cite)
    return [("arm-gateway", s, c, cite) for (s, c), cite in sorted(seen.items())]


def extract_lro():
    """LRO poll-route error codes (arm-gateway surface, 200 poll body).

    The only wire-visible error code in lro.ex is the typed error member of the
    terminal Failed record that the incomplete-record fence (lens-9 cycle-1)
    flips an InProgress record to: it is emitted with HTTP 200 (poll success)
    with status "Failed", not an error envelope — so the row carries HTTP 200
    and the meaning states the wire shape explicitly. Extraction is mechanical:
    the "code" literal inside the evaluate/2 fallback's error map.
    """
    rows = []
    src = LRO.read_text()
    # anchor is def/p-def tolerant: a sibling refactor may promote the clause
    # from defp to def (witnessed 2026-10-15, v26.10.14 lane 14)
    offset = src.find("defp evaluate(")
    if offset < 0:
        offset = src.index("def evaluate(")
    m = re.search(r'"code"\s*=>\s*"([A-Za-z][A-Za-z0-9]*)"', src[offset:])
    if not m:
        sys.stderr.write(
            "gen_error_codes: lro.ex no longer carries a literal \"code\" member "
            "in its evaluate/2 fallback — update the LRO extraction pattern.\n"
        )
        sys.exit(1)
    rows.append((200, m.group(1), f"{LRO.relative_to(ROOT)}:{line_of(src, offset + m.start())}"))
    seen = {}
    for status, code, cite in rows:
        seen.setdefault((status, code), cite)
    return [("arm-gateway", s, c, cite) for (s, c), cite in sorted(seen.items())]


def extract_egress():
    rows = []
    # Egress-refactor hardening (runtime-contracts lens 4): the pending-status
    # pairing above is heuristic. A refactor that moves a "code" literal out of
    # the 400-char window of its send site, or renames send_json, must emit a
    # LOUD failure here — never a silent `| egress | ? |` row in the generated
    # doc (that row would claim a status the parser could not witness).
    # Compliance-surface "?" rows are by design (the corpus pins the code, not
    # the status); egress-surface "?" rows are NOT.
    unresolved: list[str] = []
    src = EGRESS.read_text()
    lines = src.split("\n")
    pending_status = None
    pending_line = None
    last_send_pos = -10**9
    pos = 0
    for i, line in enumerate(lines):
        m = re.search(r'(?:send_(?:json|resp)|blob_error)\((?:conn,\s*)?(\d+),', line)
        if m:
            pending_status = int(m.group(1))
            pending_line = i + 1
            last_send_pos = pos + m.start()
        # Code literals inside helper *definitions* (defp ..._error do) are
        # skipped here: they are emitted with a fixed status added separately
        # below, and pairing them with whatever send_json preceded the defp
        # mislabels the status.
        # R143 follow-up: version-gate helpers (check_*_api_version) return
        # error tuples consumed by the caller's send_json, so their "code"
        # literals get the helper's fixed status, not the caller's pending one.
        in_helper_def = any(
            re.search(r'defp\s+\w*(error|api_version)', l) for l in lines[max(0, i - 14):i + 1]
        )
        for cm in re.finditer(r'"code"\s*=>\s*"([A-Za-z][A-Za-z0-9-]*)"', line):
            cite = f"{EGRESS.relative_to(ROOT)}:{i + 1}"
            if not in_helper_def and pending_status is not None and (pos + cm.start() - last_send_pos) < 400:
                rows.append((pending_status, cm.group(1), cite))
            elif not in_helper_def:
                # Forward pairing (lens-6): a documented explanatory comment
                # between the body build and its send pushes the "code" literal
                # beyond the 400-char BACKWARD window while the send
                # (send_resp/send_json/blob_error) FOLLOWS the literal
                # (witnessed: egress_router.ex InvalidRange 416, whose
                # lens-6 divergence note sits between encode and send).
                # Pair with the FIRST send status within the next 800 chars —
                # still loud-fail if none (never a silent ?-status row).
                forward = re.search(
                    r'(?:send_(?:json|resp)|blob_error)\((?:conn,\s*)?(\d+),',
                    src[pos + cm.end(): pos + cm.end() + 800],
                )
                if forward:
                    rows.append((int(forward.group(1)), cm.group(1), cite))
                else:
                    unresolved.append(f"{cite}: code \"{cm.group(1)}\" has no paired send status")
        for nm in re.finditer(r'not_found_error\("([A-Za-z][A-Za-z0-9]*)"\)', line):
            cite = f"{EGRESS.relative_to(ROOT)}:{i + 1}"
            rows.append((404, nm.group(1), cite))
        pos += len(line) + 1
    # helper-defined envelopes
    for code, status in [
        ("RouteNotReady", 503),
        ("InvalidBody", 400),
        ("InvalidCloudEvent", 400),
        ("InvalidQueryParameterValue", 400),
        ("InvalidApiVersion", 400),  # check_akv/check_sentinel_api_version gates (R143)
        ("InvalidEventGridEvent", 400),  # invalid_eg1_event_error/0 (EG1 schema gate)
    ]:
        cite = f"{EGRESS.relative_to(ROOT)}:{line_of(src, src.index(f'\"{code}\"'))}"
        rows.append((status, code, cite))
    # blob_route guard + rescue envelope
    for code, status in [
        ("MissingXMsVersion", 400),
        ("BlobResponseEncodeFailure", 500),
    ]:
        m = re.search(rf'"{code}"', src)
        rows.append((status, code, f"{EGRESS.relative_to(ROOT)}:{line_of(src, m.start())}"))
    # dedupe by (status, code)
    if unresolved:
        sys.stderr.write(
            "gen_error_codes: UNRESOLVED_STATUS in egress_router.ex — "
            "a \"code\" literal has no paired send status within the pairing "
            "window. Fix the extraction patterns or the source; do NOT ship a "
            "?-status egress row.\n"
        )
        for u in unresolved:
            sys.stderr.write(f"  {u}\n")
        sys.exit(1)
    seen = {}
    for status, code, cite in rows:
        seen.setdefault((status, code), cite)
    return [("egress", s, c, cite) for (s, c), cite in sorted(seen.items(), key=lambda kv: (str(kv[0][0]), kv[0][1]))]


