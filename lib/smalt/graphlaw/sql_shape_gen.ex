defmodule Smalt.GraphLaw.SqlShapeGen do
  @moduledoc """
  SQLD-5: auto-shape generation from a projected relational schema —
  "rules arrive with the schema".

  Given a projected relational schema (the shape duckdb's `DESCRIBE`
  reports: table name, columns with SQL type and NULL flag, optional
  primary-key flag from `duckdb_constraints()`), generate SHACL shapes
  governing the ingested data, emitted as Turtle in exactly the grammar
  `Smalt.GraphLaw.Validator.ShapeFile` parses (and therefore the same
  grammar GL-2's law compiler consumes):

    * `sh:datatype` per column type — INTEGER family -> `xsd:integer`,
      VARCHAR/TEXT family -> `xsd:string`, BOOLEAN family ->
      `xsd:boolean`
    * `sh:minCount 1` for every NOT NULL column (NULLABLE columns get NO
      minCount — SHACL semantics: absent means optional, KD-156-consistent)
    * primary-key columns get `sh:minCount 1` plus an identifier-pattern
      message (`sh:message`), within the substrate grammar's constraint
      vocabulary (path/minCount/maxCount/datatype/message)

  SQL types with no xsd counterpart in the substrate grammar (DOUBLE,
  FLOAT, REAL, DECIMAL, DATE, TIMESTAMP, BLOB, LIST, STRUCT, ...) are a
  typed `ArgumentError` naming the type — the generator refuses to
  silently widen a governed column to string.

  The court (`test/integration/sqld5_sql_shape_court_test.exs`) generates
  from a 3-table schema, parses the emitted Turtle with the substrate's
  own `ShapeFile.parse!/2`, and drives `Validator.validate_shape/2`:
  conforming rows pass; NULL in NOT NULL, string-in-int, and unknown
  column all refuse.
  """

  # -- schema model ------------------------------------------------------------
  # schema = [%{table: String.t(),
  #             columns: [%{name: String.t(), type: String.t(),
  #                         null: boolean() | "YES" | "NO", pk: boolean() | nil}]}]
  # `null` mirrors duckdb DESCRIBE's NULL column ("YES" -> nullable).

  @integer_types ~w(INTEGER BIGINT SMALLINT TINYINT HUGEINT UTINYINT USMALLINT UBIGINT INT INT4 INT8)
  @string_types ~w(VARCHAR TEXT STRING CHAR BPCHAR)
  @boolean_types ~w(BOOLEAN BOOL)

  @doc """
  Generate the SHACL Turtle for `schema`. Deterministic: identical input
  -> byte-identical output.
  """
  @spec generate(list(map())) :: String.t()
  def generate(schema) when is_list(schema) and schema != [] do
    schema
    |> Enum.map(&table_shape/1)
    |> Enum.join("\n")
    |> then(&(header() <> &1))
  end

  @doc """
  Parse generated Turtle back into the substrate shape map via
  `Smalt.GraphLaw.Validator.ShapeFile.parse!/2` — the generated text is
  consumed by the SAME parser the compiled shapes file uses, so the
  generated governance can never drift from the admission gate.
  """
  def parse(ttl) when is_binary(ttl) do
    Smalt.GraphLaw.Validator.ShapeFile.parse!(ttl, "generated-sql-shapes.ttl")
  end

  @doc """
  Map a duckdb column type to the substrate `sh:datatype` family atom.
  Raises ArgumentError on types with no substrate counterpart.
  """
  def datatype_for(sql_type) when is_binary(sql_type) do
    case normalized(sql_type) do
      t when t in @integer_types -> :integer
      t when t in @string_types -> :string
      t when t in @boolean_types -> :boolean

      other ->
        raise ArgumentError,
              "no substrate sh:datatype for SQL type #{inspect(other)} " <>
                "(supported: INTEGER family -> xsd:integer, VARCHAR family -> xsd:string, " <>
                "BOOLEAN family -> xsd:boolean)"
    end
  end

  # -- per-table emission --------------------------------------------------------

  defp header do
    """
    # Generated by Smalt.GraphLaw.SqlShapeGen (SQLD-5) — DO NOT HAND-EDIT.
    # Prefix bindings (the substrate ShapeFile subset needs no @prefix lines):
    #   sh:     http://www.w3.org/ns/shacl#
    #   xsd:    http://www.w3.org/2001/XMLSchema#
    #   smalt:  https://ggen.io/ontology/smalt#
    """
  end

  defp table_shape(%{table: table, columns: cols} = spec)
       when is_binary(table) and is_list(cols) do
    shape_name = "smalt:Sql#{camelize(table)}Shape"
    target_class = "smalt:sql_#{camelize(table)}"

    props =
      cols
      |> Enum.map(&property_block(table, &1))
      |> Enum.join(" ,\n        ")

    closed =
      if Map.get(spec, :closed, true) do
        "    sh:closed true ;\n"
      else
        ""
      end

    """
    \n#{shape_name} a sh:NodeShape ;
    #{closed}    sh:targetClass #{target_class} ;
        sh:property #{props} .
    """
  end

  defp table_shape(spec) do
    raise ArgumentError,
          "invalid table spec #{inspect(spec)} (expected %{table: binary, columns: list})"
  end

  defp property_block(table, %{name: name, type: type} = col) when is_binary(name) do
    datatype = Atom.to_string(datatype_for(type))
    nullable = nullable?(col)
    pk? = Map.get(col, :pk, false) == true

    {constraints, message} =
      if nullable do
        # SHACL semantics (KD-156): no sh:minCount on a nullable column.
        {"sh:datatype xsd:" <> datatype, nil}
      else
        {"sh:datatype xsd:" <> datatype <> " ; sh:minCount 1", "NOT NULL column #{table}.#{name}"}
      end

    message =
      if pk? do
        "primary key identifier for #{table}.#{name} (non-empty, unique)"
      else
        message
      end

    if message do
      "[ sh:path smalt:#{name} ; #{constraints} ; sh:message \"#{message}\" ]"
    else
      "[ sh:path smalt:#{name} ; #{constraints} ]"
    end
  end

  defp property_block(_table, spec) do
    raise ArgumentError,
          "invalid column spec #{inspect(spec)} (expected %{name: binary, type: binary})"
  end

  # -- helpers -------------------------------------------------------------------

  defp nullable?(%{null: null}), do: null in [nil, true, "YES", "yes", "y"]
  defp nullable?(_), do: false

  defp normalized(type), do: String.upcase(String.trim(type))

  defp camelize(name) do
    name
    |> String.split(["_", "-", " "], trim: true)
    |> Enum.map(&String.capitalize/1)
    |> Enum.join()
  end
end
