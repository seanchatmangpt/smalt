defmodule Smalt.AshExtension.SubstrateResource.Verify do
  @moduledoc """
  Verifier for `smalt`: enforces 2 legality constraint(s) against the compiled
  `:smalt_compiled` state.

  Generated by ash-extension-pack verify.ex.tmpl from an admitted
  `aex:AshExtensionSpec` (/tmp/smalt-aex/spec.ttl, spec IRIs recorded in
  docs/PACK_INTEGRATION/ash-extension.md), then HAND-ADAPTED (disclosed): the
  template leaves each aex:Verifier body as a declared-open gap; the two bodies
  below are the real constraint implementations, and `check_read_only_surface/1`
  was re-pointed from the compiled struct to `dsl_state` so the constraint can
  inspect the resource's compiled Ash actions.
  """
  use Spark.Dsl.Verifier

  # Matter-scope vocabulary. Smalt's matter-isolation law (Smalt.Projection.Admission,
  # Smalt.Telemetry) scopes matter to privacy tags; the read surface carries the same
  # two-value vocabulary, defaulting to least privilege.
  @matter_scope_vocab [:private, :public]

  @impl true
  def verify(dsl_state) do
    case Spark.Dsl.Verifier.get_persisted(dsl_state, :smalt_compiled) do
      nil ->
        {:error,
         Spark.Error.DslError.exception(
           message:
             "smalt: transformer did not persist :smalt_compiled -- Persist must run before Verify",
           path: []
         )}

      compiled ->
        with :ok <- check_read_only_surface(dsl_state),
             :ok <- check_store_table_declared(compiled) do
          :ok
        end
    end
  end

  # Only read actions permitted (matter-isolation: read-only surface).
  defp check_read_only_surface(dsl_state) do
    dsl_state
    |> Spark.Dsl.Verifier.get_entities([:actions])
    |> Enum.reduce_while(:ok, fn action, :ok ->
      if action_type(action) == :read do
        {:cont, :ok}
      else
        {:halt,
         {:error,
          Spark.Error.DslError.exception(
            message:
              "smalt substrate_resource: only read actions are permitted (matter-isolation: " <>
                "read-only surface); refusing action #{inspect(action.name)} of type " <>
                "#{inspect(action_type(action))}",
            path: [:actions, action.name]
          )}}
      end
    end)
  end

  defp action_type(action), do: Map.get(action, :type)

  # store_table must be a declared, well-formed Store table name; matter_scope
  # (when present) must be drawn from the matter-scope vocabulary.
  defp check_store_table_declared(compiled) do
    case Map.get(compiled, :substrate, []) do
      [%{store_table: table} = entry] when is_atom(table) and table != nil ->
        with :ok <- check_table_name(table),
             :ok <- check_matter_scope(Map.get(entry, :matter_scope)) do
          :ok
        end

      [] ->
        {:error,
         Spark.Error.DslError.exception(
           message: "smalt substrate_resource: no `substrate` section declared",
           path: [:substrate]
         )}

      other ->
        {:error,
         Spark.Error.DslError.exception(
           message: "smalt substrate_resource: expected exactly one substrate declaration, got #{inspect(other)}",
           path: [:substrate]
         )}
    end
  end

  defp check_table_name(table) when is_atom(table) and table != nil do
    if table |> Atom.to_string() |> String.starts_with?("smalt_") do
      :ok
    else
      {:error,
       Spark.Error.DslError.exception(
         message:
           "smalt substrate_resource: store_table #{inspect(table)} is outside the smalt_ Store table namespace",
         path: [:substrate]
       )}
    end
  end

  defp check_matter_scope(nil), do: :ok
  defp check_matter_scope([]), do: :ok

  defp check_matter_scope(scopes) when is_list(scopes) do
    unknown = Enum.reject(scopes, &(&1 in @matter_scope_vocab))

    if unknown == [] do
      :ok
    else
      {:error,
       Spark.Error.DslError.exception(
         message:
           "smalt substrate_resource: matter_scope #{inspect(unknown)} outside vocabulary #{inspect(@matter_scope_vocab)}",
         path: [:substrate]
       )}
    end
  end
end