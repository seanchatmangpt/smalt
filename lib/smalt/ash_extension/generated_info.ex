defmodule Smalt.AshExtension.SubstrateResource.Info do
  @moduledoc """
  Public introspection API for `smalt`.

  Generated by ash-extension-pack info.ex.tmpl, then HAND-ADAPTED (disclosed):
  the singleton-entity unwrap in `store_table_result/1` / `matter_scope_result/1`
  (the template getter projects the raw section entity list; the adaptation
  projects the singleton entity's field, with `[]` as the least-privilege
  matter-scope default).
  """

  @doc "Returns the raw `:substrate` DSL entities declared on `resource`."
  def substrate(resource) do
    Spark.Dsl.Extension.get_entities(resource, [:substrate])
  end

  @doc "Returns the transformer-normalized compiled state for `resource`, or `nil` if the extension is not present."
  def compiled(resource) do
    case compiled_result(resource) do
      {:ok, compiled} -> compiled
      {:error, _} -> nil
    end
  end

  @doc """
  Returns `{:ok, compiled}` or `{:error, :not_compiled}` for `resource`.

  """
  def compiled_result(resource) do
    case Spark.Dsl.Extension.get_persisted(resource, :smalt_compiled, nil) do
      nil -> {:error, :not_compiled}
      compiled -> {:ok, compiled}
    end
  end

  @doc "Bang variant of `compiled_result/1` -- raises `ArgumentError` instead of returning `{:error, _}`."
  def compiled!(resource) do
    case compiled_result(resource) do
      {:ok, compiled} ->
        compiled

      {:error, reason} ->
        raise ArgumentError,
              "Smalt.AshExtension.SubstrateResource.Info.compiled!/1: #{inspect(reason)}"
    end
  end

  @doc "Predicate: does `resource` carry compiled `smalt` state?"
  def compiled?(resource) do
    match?({:ok, _}, compiled_result(resource))
  end

  @doc "Returns the `:substrate`-derived `matter_scope`, or `nil` if `resource` has no compiled `smalt` state."
  def matter_scope(resource) do
    case matter_scope_result(resource) do
      {:ok, value} -> value
      {:error, :not_found} -> nil
    end
  end

  @doc "Returns `{:ok, matter_scope}` or `{:error, :not_found}` for `resource`'s `:substrate` section."
  def matter_scope_result(resource) do
    case compiled_result(resource) do
      {:ok, %{substrate: [entity]}} -> {:ok, entity.matter_scope || []}
      {:ok, _compiled} -> {:error, :not_found}
      {:error, _} = error -> error
    end
  end

  @doc "Bang variant of `matter_scope_result/1` -- raises `ArgumentError` instead of returning `{:error, _}`."
  def matter_scope!(resource) do
    case matter_scope_result(resource) do
      {:ok, value} ->
        value

      {:error, reason} ->
        raise ArgumentError,
              "Smalt.AshExtension.SubstrateResource.Info.matter_scope!/1: #{inspect(reason)}"
    end
  end

  @doc "Predicate: does `resource` carry a `matter_scope`?"
  def matter_scope?(resource) do
    match?({:ok, _}, matter_scope_result(resource))
  end

  @doc "Returns the `:substrate`-derived `store_table`, or `nil` if `resource` has no compiled `smalt` state."
  def store_table(resource) do
    case store_table_result(resource) do
      {:ok, value} -> value
      {:error, :not_found} -> nil
    end
  end

  @doc "Returns `{:ok, store_table}` or `{:error, :not_found}` for `resource`'s `:substrate` section."
  def store_table_result(resource) do
    case compiled_result(resource) do
      {:ok, %{substrate: [entity]}} -> {:ok, entity.store_table}
      {:ok, _compiled} -> {:error, :not_found}
      {:error, _} = error -> error
    end
  end

  @doc "Bang variant of `store_table_result/1` -- raises `ArgumentError` instead of returning `{:error, _}`."
  def store_table!(resource) do
    case store_table_result(resource) do
      {:ok, value} ->
        value

      {:error, reason} ->
        raise ArgumentError,
              "Smalt.AshExtension.SubstrateResource.Info.store_table!/1: #{inspect(reason)}"
    end
  end

  @doc "Predicate: does `resource` carry a `store_table`?"
  def store_table?(resource) do
    match?({:ok, _}, store_table_result(resource))
  end
end
