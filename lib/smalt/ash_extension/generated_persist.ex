defmodule Smalt.AshExtension.SubstrateResource.Persist do
  @moduledoc """
  Transformer for `smalt`: normalizes the raw `:substrate`
  DSL entities into a compiled struct and persists it as `:smalt_compiled`.

  Generated by ash-extension-pack persist.ex.tmpl, then HAND-ADAPTED
  (disclosed): the template reads `get_entities/2` for the section, but
  `:substrate` declares schema FIELDS (no entities), and Spark stores section
  fields as section OPTIONS, not entities. The adaptation reads the section
  options via `Spark.Dsl.Transformer.get_option/3` and persists a normalized
  singleton map so the generated Verify/Info modules read the SAME compiled
  shape (`%{substrate: [%{store_table: atom, matter_scope: [atom]}]}`).
  """
  use Spark.Dsl.Transformer

  @impl true
  def transform(dsl_state) do
    store_table = Spark.Dsl.Transformer.get_option(dsl_state, [:substrate], :store_table)
    matter_scope = Spark.Dsl.Transformer.get_option(dsl_state, [:substrate], :matter_scope)

    persisted = %{
      substrate: [
        %{store_table: store_table, matter_scope: matter_scope}
      ],
      metadata: %{source: :smalt_store_read}
    }

    {:ok, Spark.Dsl.Transformer.persist(dsl_state, :smalt_compiled, persisted)}
  end
end
