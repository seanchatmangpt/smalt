#!/usr/bin/env bash
# parallel-matrix.sh — AZB-02 per-container-netns burn matrix driver.
#
# Matrix spec (AZB-02): planes=(control data integration identity all) x
# replicas 1..N. compose.burn.yml is GENERATED from this spec — not
# hand-listed. ggen has no compose templating pack in this tree
# (UNSUPPORTED(generator-capability), recorded in azb-02-netns.md), so the
# template lives here and the checked-in compose.burn.yml is its output for
# the default N=8 (SMALT_RING_REPLICAS / the AZB-22 ring default; the
# historical default was N=4).
#
# Preflight (AZB-02 anti-vacuity contract): `docker compose config` on the
# burn project must show ZERO published host ports. Any `published:` key in
# the resolved config => exit 2 HOST_PORT_PUBLISH_REFUSED, before any
# container runs. This is the non-vacuity gate for the zero-publish law: a
# compose that publishes 9443:9443 is refused loudly, never silently run.
#
# Per-container probe: docker/burn/container-burn.sh (release boot, netns
# `ss -ltn` listener assertion, AMQP atom-flood where the AMQP listener
# exists). Falsifier of the netns law: any two containers' listeners
# conflicting on the host, or a host listener on a canonical port — the
# driver asserts the host side is empty after a green run.
#
# Exit 0 clean / 1 not all-clean / 2 preflight refusal / 3 usage.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
cd "$ROOT"

COMPOSE_FILE="$HERE/compose.burn.yml"
PROJECT="smalt-burn"
RESULTS_DIR="$HERE/results"
PLANES=(control data integration identity all)

usage() {
  cat <<EOF
usage: parallel-matrix.sh [--plane P] [--replicas N] [--dry-run] [--emit-compose [N]] [--deadline S]
  --plane P        run only plane P's replica row (default: run only 'all')
  --replicas N     replica count for --emit-compose AND for the run row
                   (default 4; AZB-17/22 run N=8 of plane 'all')
  --emit-compose   (re)generate docker/burn/compose.burn.yml from the matrix
                   spec and exit 0 (this file is generated, never hand-edited)
  --dry-run        print the resolved plan and exit 0
  --deadline S     wall budget in seconds, default 900
Exit: 0 clean / 1 not all clean / 2 HOST_PORT_PUBLISH_REFUSED preflight / 3 usage
EOF
  exit 3
}

DRY_RUN=0
EMIT=0
DEADLINE_SECS=900
PLANE="all"
REPLICAS=4
while [ $# -gt 0 ]; do
  case "$1" in
    --plane) PLANE="$2"; shift ;;
    --replicas) REPLICAS="$2"; shift ;;
    --dry-run) DRY_RUN=1 ;;
    --emit-compose) EMIT=1; if [ "${2:-}" ] && [ "${2:-}" != "--" ]; then case "$2" in ''|*[!0-9]*) ;; *) REPLICAS="$2"; shift ;; esac; fi ;;
    --deadline) DEADLINE_SECS="$2"; shift ;;
    *) usage ;;
  esac
  shift
done

for p in $PLANE; do
  case " ${PLANES[*]} " in *" $p "*) ;; *) echo "[BURN-MATRIX] unknown plane $p" >&2; exit 3 ;; esac
done

svc_name() { printf 'smalt-burn-%s-%s' "$1" "$2"; }

# --- generator: matrix spec -> compose.burn.yml ------------------------------
emit_compose() {
  local n="$1"
  echo "# compose.burn.yml — GENERATED by docker/burn/parallel-matrix.sh --emit-compose $n"
  echo "# (AZB-02 matrix spec: planes=(control data integration identity all) x 1..N)."
  echo "# Do not hand-edit; regenerate. Zero 'ports:' publish — every container is"
  echo "# its own network namespace; canonical ports bind inside the netns only."
  cat <<'HDR'
x-burn-common: &burn-common
  image: smalt:local
  entrypoint: ["bash", "/burn/container-burn.sh"]
  volumes:
    - ../burn:/burn:ro
    - ./results:/burn-results
    - /Users/sac/beam4pm:/beam4pm:ro
    - /Users/sac/xaas:/xaas:ro
  tmpfs:
    - /tmp
  cap_drop: [ALL]
  security_opt: [no-new-privileges:true]
  restart: "no"

services:
HDR
  local p i s
  for p in "${PLANES[@]}"; do
    for i in $(seq 1 "$n"); do
      s="$(svc_name "$p" "$i")"
      case "$p" in
        control|all) exp=9443 ;;
        data) exp=8443 ;;
        integration) exp=5672 ;;
        identity) exp=9443 ;;
      esac
      # SMALT_PLANES is set ONLY for single-plane services; 'all' is the
      # unset default (the loader refuses the literal :all).
      if [ "$p" = all ]; then planes_line=""; else planes_line="      SMALT_PLANES: $p"$'\n'; fi
      cat <<SVC
  $s:
    <<: *burn-common
    environment:
      BURN_SERVICE: $s
$planes_line      BURN_EXPECT_PORT: "$exp"
      BURN_FLOOD_SECONDS: "15"
      SMALT_BURN_SUBJECT_SHA: \${SMALT_BURN_SUBJECT_SHA:-}
      BURN_IMAGE_DIGEST: \${BURN_IMAGE_DIGEST:-}

SVC
    done
  done
}

if [ "$EMIT" = 1 ]; then
  emit_compose "$REPLICAS" > "$COMPOSE_FILE"
  echo "[BURN-MATRIX] generated $COMPOSE_FILE (planes=${PLANES[*]} replicas=$REPLICAS)"
  exit 0
fi

DC=(docker compose -f "$COMPOSE_FILE" -p "$PROJECT")

# --- preflight: zero host port publish, fail-closed --------------------------
preflight() {
  mkdir -p "$RESULTS_DIR"
  command -v docker >/dev/null 2>&1 || { echo "[BURN-MATRIX] docker not on PATH" >&2; exit 2; }
  docker info >/dev/null 2>&1 || { echo "[BURN-MATRIX] docker daemon not reachable" >&2; exit 2; }
  docker image inspect smalt:local >/dev/null 2>&1 || {
    echo "[BURN-MATRIX] image smalt:local missing — build per docker/BUILD_RECEIPT.md first" >&2
    exit 2
  }
  local resolved pubs
  resolved="$("${DC[@]}" config 2>/dev/null)" || { echo "[BURN-MATRIX] compose config failed" >&2; exit 2; }
  pubs="$(printf '%s\n' "$resolved" | grep -c 'published:' || true)"
  if [ "$pubs" -ne 0 ]; then
    echo "[BURN-MATRIX] HOST_PORT_PUBLISH_REFUSED — $pubs published host port(s) in $COMPOSE_FILE" >&2
    printf '%s\n' "$resolved" | grep -n 'published:' >&2
    exit 2
  fi
  echo "[BURN-MATRIX] preflight OK: 0 published host ports (netns isolation)"
  # Baseline the host's own listeners (a dev substrate may legitimately hold
  # canonical ports); the falsifier asserts no NEW host listeners post-run.
  lsof -nP -iTCP -sTCP:LISTEN 2>/dev/null | awk '{print $9}' | sort -u \
    > "$RESULTS_DIR/host-baseline.txt" || true
}

# Services under test for this run: the plane's replica row.
SERVICES=()
i=1
while [ $i -le "$REPLICAS" ]; do SERVICES+=("$(svc_name "$PLANE" "$i")"); i=$((i + 1)); done

if [ "$DRY_RUN" = 1 ]; then
  echo "[BURN-MATRIX][DRY-RUN] compose_file=$COMPOSE_FILE project=$PROJECT"
  echo "[BURN-MATRIX][DRY-RUN] services=${SERVICES[*]}"
  echo "[BURN-MATRIX][DRY-RUN] results_dir=$RESULTS_DIR deadline=${DEADLINE_SECS}s"
  echo "[BURN-MATRIX][DRY-RUN] plan: preflight -> compose up -d -> deadline-poll burn-<svc>.jsonl x$REPLICAS -> assert $REPLICAS/$REPLICAS clean -> host lsof assert -> compose down"
  exit 0
fi

preflight

mkdir -p "$RESULTS_DIR"
rm -f "$RESULTS_DIR"/burn-smalt-burn-*.jsonl "$RESULTS_DIR"/flood-count-* 2>/dev/null || true

echo "[BURN-MATRIX] compose up -d (${SERVICES[*]})"
"${DC[@]}" up -d "${SERVICES[@]}"

START_TS=$SECONDS
DEADLINE=$((START_TS + DEADLINE_SECS))
collect() { # poll until every service has a JSONL row or the deadline hits
  have=0
  while [ "$SECONDS" -lt "$DEADLINE" ]; do
    have=0
    for s in "${SERVICES[@]}"; do
      [ -s "$RESULTS_DIR/burn-$s.jsonl" ] && have=$((have + 1))
    done
    if [ "$have" -eq "${#SERVICES[@]}" ]; then
      echo "[BURN-MATRIX] all ${#SERVICES[@]} JSONL rows present after $((SECONDS - START_TS))s"
      return 0
    fi
    read -t 2 -u 0 _ </dev/null 2>/dev/null || true
  done
  echo "[BURN-MATRIX] deadline (${DEADLINE_SECS}s) before all rows landed (have=$have/$REPLICAS)" >&2
  return 1
}

COLLECT_RC=0
collect || COLLECT_RC=$?

echo "[BURN-MATRIX] container states at collection:"
"${DC[@]}" ps -a --format '{{.Name}} {{.State}} {{.ExitCode}}' || true

# Falsifier witness: capture in-netns ss lines before teardown.
echo "[BURN-MATRIX] in-netns listeners (ss -ltn) per container:"
for s in "${SERVICES[@]}"; do
  echo "--- $s"
  docker compose -f "$COMPOSE_FILE" -p "$PROJECT" exec -T "$s" ss -ltn 2>/dev/null || true
done

# Down + teardown BEFORE verdict so cleanup happens on every path.
"${DC[@]}" down -v --remove-orphans >/dev/null 2>&1 || true

if [ "$COLLECT_RC" -ne 0 ]; then
  echo "[BURN-MATRIX] VERDICT: FAIL — not all containers emitted rows" >&2
  exit 1
fi

CLEAN=0
for s in "${SERVICES[@]}"; do
  row="$(tail -1 "$RESULTS_DIR/burn-$s.jsonl")"
  echo "[BURN-MATRIX] $s -> $row"
  case "$row" in
    *'"clean":true'*) CLEAN=$((CLEAN + 1)) ;;
  esac
done

# Host-side falsifier check: after down, no NEW host listener on a canonical
# smalt port vs the pre-run baseline (the netns law's host half).
lsof -nP -iTCP -sTCP:LISTEN 2>/dev/null | awk '{print $9}' | sort -u \
  > "$RESULTS_DIR/host-after.txt" || true
HOST_HITS=0
for port in 9443 9444 8443 5672 5673 9545; do
  if grep -q ":$port " "$RESULTS_DIR/host-after.txt" && ! grep -q ":$port " "$RESULTS_DIR/host-baseline.txt"; then
    echo "[BURN-MATRIX] HOST PORT CONFLICT: new host listener on $port after run" >&2
    HOST_HITS=$((HOST_HITS + 1))
  fi
done
[ "$HOST_HITS" -eq 0 ] || { echo "[BURN-MATRIX] VERDICT: FAIL — new host listeners on canonical ports" >&2; exit 1; }

echo "[BURN-MATRIX] clean services: $CLEAN/$REPLICAS; new host canonical-port listeners: 0 (baseline preserved)"
[ "$CLEAN" -eq "$REPLICAS" ] || { echo "[BURN-MATRIX] VERDICT: FAIL — not $REPLICAS/$REPLICAS clean" >&2; exit 1; }
echo "[BURN-MATRIX] VERDICT: CLEAN — 4/4 containers green, netns-isolated, zero host publish"
