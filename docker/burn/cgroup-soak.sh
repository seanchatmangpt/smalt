#!/usr/bin/env bash
# cgroup-soak.sh — AZB-18 cgroup-constrained soak (docker/burn).
#
# Compose-based soak with PER-SERVICE cgroup limits (the AZB-18 burn design:
# control=2.0, data=1.5, integration=2.0, identity=1.0 CPU; mem_limit 4g
# (2g was insufficient for the 2.0-CPU planes — OOM exit 137, see
# azb-18-cgroup-soak.md cycle 2);
# pids_limit 512 per ticket). Each service runs the OFFLINE suite inside its
# container under its own throttling (suite self-boots on ephemeral ports, so
# 4 parallel containers in their own netns never collide). Per-service row
# files are merged into one smalt-burn/v2 JSONL with a run_header (the
# EXPECTED matrix validate_burn --gate checks against) + a run_receipt line,
# then validated: `python3 scripts/validate_burn.py --gate <file>`.
#
# Failures classify against docs/jira/v26.10.17/FLAKE_LEDGER.md host-side;
# any UNLEDGERED face => RED (new ledger row first, then re-burn).
#
# compose.cgroup.yml is GENERATED by this script's --emit-compose (never
# hand-edited). Zero 'ports:' publish — every container is its own netns.
#
# Exit 0 clean / 1 burn failure (dirty row, MISSING_CELL, or unledgered face)
# / 2 preflight refusal / 3 usage.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
cd "$ROOT"

PROJECT="smalt-cgroup-soak"
COMPOSE_FILE="$HERE/compose.cgroup.yml"
RESULTS_DIR="$HERE/results"
PLANES=(control data integration identity)
# AZB-18 burn design per-service CPU caps (control/data/integration/identity)
CPUS_CONTROL=2.0
CPUS_DATA=1.5
CPUS_INTEGRATION=2.0
CPUS_IDENTITY=1.0
MEM_LIMIT="${SMALT_SOAK_MEM_LIMIT:-4g}"
PIDS_LIMIT="${SMALT_SOAK_PIDS_LIMIT:-512}"
TEST_IMG="${SMALT_BURN_TEST_IMAGE:-smalt-burn:latest}"
LEDGER="$ROOT/docs/jira/v26.10.17/FLAKE_LEDGER.md"
BURN_DIR="$ROOT/docs/jira/v26.10.18/burn"

DRY_RUN=0
EMIT=0
CYCLES=1
JSONL=""
DEADLINE_SECS=3600

usage() {
  cat <<EOF
usage: cgroup-soak.sh [--cycles N] [--jsonl PATH] [--dry-run] [--emit-compose] [--deadline S]
  --cycles N       offline-suite cycles per service, default 1
                   (AZB-18 accept is 3 rounds x 3 quota tiers; the per-service
                   CPU ladder here is the burn design's fixed 2.0/1.5/2.0/1.0)
  --jsonl PATH     merged smalt-burn/v2 sink (default
                   docs/jira/v26.10.18/burn/cgroup-<ts>.jsonl — tracked, never tmp/,
                   per burn-row.schema.json R_missing_replay note)
  --dry-run        print the resolved plan and exit 0
  --emit-compose   (re)generate docker/burn/compose.cgroup.yml and exit 0
  --deadline S     overall wall budget in seconds, default 3600
Exit: 0 clean / 1 burn failure / 2 preflight refusal / 3 usage
EOF
  exit 3
}

while [ $# -gt 0 ]; do
  case "$1" in
    --cycles) CYCLES="$2"; shift ;;
    --jsonl) JSONL="$2"; shift ;;
    --dry-run) DRY_RUN=1 ;;
    --emit-compose) EMIT=1 ;;
    --deadline) DEADLINE_SECS="$2"; shift ;;
    *) usage ;;
  esac
  shift
done

case "$CYCLES" in ''|*[!0-9]*) usage ;; esac
[ "$CYCLES" -ge 1 ] || usage

TS="$(date -u +%Y%m%dT%H%M%SZ)"
START_TS="$SECONDS"

# --- compose generator --------------------------------------------------------
emit_compose() {
  echo "# compose.cgroup.yml — GENERATED by docker/burn/cgroup-soak.sh (AZB-18)."
  echo "# Per-service cgroup limits: control=$CPUS_CONTROL data=$CPUS_DATA"
  echo "# integration=$CPUS_INTEGRATION identity=$CPUS_IDENTITY CPU;"
  echo "# mem_limit=$MEM_LIMIT; pids_limit=$PIDS_LIMIT. Do not hand-edit; regenerate."
  echo "# Zero 'ports:' publish — every container is its own netns."
  cat <<'HDR'
x-soak-common: &soak-common
  image: smalt-burn:latest
  entrypoint: ["bash", "/burn/cgroup_suite_runner.sh"]
  environment: &soak-env
    BURN_CYCLES: ${BURN_CYCLES:-1}
    SMALT_BURN_SUBJECT_SHA: ${SMALT_BURN_SUBJECT_SHA:-}
    BURN_IMAGE_DIGEST: ${BURN_IMAGE_DIGEST:-}
    MIX_BUILD_ROOT: _build-cgroup-soak
  volumes:
    - ../burn:/burn:ro
    - ./results:/burn-results
    - ../../test:/smalt/test:ro
    - ../../lib:/smalt/lib:ro
    # WO-4 harness-mount-gap fix: the offline tier reads .ggen_igniter/receipts
    # (File.Error face in azb-18 cycles); mounted read-only from the sibling
    # checkout. Path is relative to THIS compose file's dir (docker/burn).
    - ../../../ggen_igniter:/burn/ggen_igniter:ro
  tmpfs:
    - /tmp
  cap_drop: [ALL]
  security_opt: [no-new-privileges:true]
  mem_limit: ${SMALT_SOAK_MEM_LIMIT:-4g}
  pids_limit: ${SMALT_SOAK_PIDS_LIMIT:-512}
  restart: "no"

services:
HDR
  local p s cpus
  for p in "${PLANES[@]}"; do
    case "$p" in
      control) cpus="$CPUS_CONTROL" ;;
      data) cpus="$CPUS_DATA" ;;
      integration) cpus="$CPUS_INTEGRATION" ;;
      identity) cpus="$CPUS_IDENTITY" ;;
    esac
    s="smalt-soak-$p"
    cat <<SVC
  $s:
    <<: *soak-common
    cpus: "$cpus"
    environment:
      <<: *soak-env
      BURN_SERVICE: $s
      BURN_PLANE: $p
      BURN_CPUS: "$cpus"
      BURN_MEM: \${SMALT_SOAK_MEM_LIMIT:-4g}
SVC
  done
}

if [ "$EMIT" = 1 ]; then
  emit_compose > "$COMPOSE_FILE"
  echo "[CGROUP-SOAK] wrote $COMPOSE_FILE"
  exit 0
fi

if [ "$DRY_RUN" = 1 ]; then
  echo "[CGROUP-SOAK][DRY-RUN] root=$ROOT cycles=$CYCLES deadline=${DEADLINE_SECS}s"
  echo "[CGROUP-SOAK][DRY-RUN] image=$TEST_IMG mem=$MEM_LIMIT pids=$PIDS_LIMIT"
  echo "[CGROUP-SOAK][DRY-RUN] cpus: control=$CPUS_CONTROL data=$CPUS_DATA integration=$CPUS_INTEGRATION identity=$CPUS_IDENTITY"
  echo "[CGROUP-SOAK][DRY-RUN] compose=$COMPOSE_FILE jsonl=${JSONL:-$BURN_DIR/cgroup-$TS.jsonl}"
  echo "[CGROUP-SOAK][DRY-RUN] plan: emit compose -> compose config + zero-publish preflight -> 4 parallel containers (own netns each) x $CYCLES offline-suite cycles under per-service cpus/mem/pids limits -> merge rows + run_header + run_receipt -> validate_burn --gate -> FLAKE_LEDGER classify"
  exit 0
fi

# --- preflight ----------------------------------------------------------------
command -v docker >/dev/null || { echo "[CGROUP-SOAK] docker missing" >&2; exit 2; }
docker compose version >/dev/null 2>&1 || { echo "[CGROUP-SOAK] docker compose missing" >&2; exit 2; }
docker image inspect "$TEST_IMG" >/dev/null 2>&1 || {
  echo "[CGROUP-SOAK] test image $TEST_IMG missing — build per docker/BUILD_RECEIPT.md" >&2
  exit 2
}

SUBJ_SHA="$(git -C "$ROOT" rev-parse HEAD 2>/dev/null || echo unrecorded)"
IMG_DIGEST="$(docker image inspect --format '{{index .RepoDigests 0}}' "$TEST_IMG" 2>/dev/null || echo unrecorded)"

mkdir -p "$RESULTS_DIR" "$BURN_DIR"
JSONL="${JSONL:-$BURN_DIR/cgroup-$TS.jsonl}"
export SMALT_BURN_SUBJECT_SHA="$SUBJ_SHA" BURN_IMAGE_DIGEST="$IMG_DIGEST" \
  BURN_CYCLES="$CYCLES" SMALT_SOAK_MEM_LIMIT="$MEM_LIMIT" SMALT_SOAK_PIDS_LIMIT="$PIDS_LIMIT"

emit_compose > "$COMPOSE_FILE"

# AZB-02 anti-vacuity contract inherited: the resolved config must parse and
# publish ZERO host ports. Any 'published:' key => HOST_PORT_PUBLISH_REFUSED.
if ! docker compose -f "$COMPOSE_FILE" -p "$PROJECT" config --quiet; then
  echo "[CGROUP-SOAK] PREFLIGHT-FAIL: compose config invalid" >&2
  exit 2
fi
if docker compose -f "$COMPOSE_FILE" -p "$PROJECT" config | grep -q 'published:'; then
  echo "[CGROUP-SOAK] PREFLIGHT-FAIL: HOST_PORT_PUBLISH_REFUSED" >&2
  exit 2
fi
# WO-4 mount-surface preflight: the resolved config MUST carry the read-only
# ggen_igniter mount (the offline tier reads .ggen_igniter/receipts; a soak
# without it produces UNLEDGERED File.Error faces — azb-18 cycle evidence).
if ! docker compose -f "$COMPOSE_FILE" -p "$PROJECT" config | grep -q 'ggen_igniter'; then
  echo "[CGROUP-SOAK] PREFLIGHT-FAIL: GGEN_IGNITER_MOUNT_MISSING" >&2
  exit 2
fi
echo "[CGROUP-SOAK] preflight OK: config valid, zero published ports, subject_sha=$SUBJ_SHA image=$IMG_DIGEST"

cleanup() { docker compose -f "$COMPOSE_FILE" -p "$PROJECT" down -v --remove-orphans >/dev/null 2>&1 || true; }
trap cleanup EXIT INT TERM

# --- run: 4 parallel containers, each throttled --------------------------------
echo "[CGROUP-SOAK] up: 4 services x $CYCLES cycle(s) under cpus 2.0/1.5/2.0/1.0 mem=$MEM_LIMIT pids=$PIDS_LIMIT"
docker compose -f "$COMPOSE_FILE" -p "$PROJECT" up -d --wait || {
  echo "[CGROUP-SOAK] containers did not reach running state" >&2
  exit 1
}

# Deadline-poll each service's row file to the expected cycle count.
poll_rows() {
  while [ "$((START_TS + DEADLINE_SECS))" -gt "$SECONDS" ]; do
    _done=1
    for p in "${PLANES[@]}"; do
      _n="$(grep -c '"stage":"soak"' "$RESULTS_DIR/cgroup-smalt-soak-$p.jsonl" 2>/dev/null || true)"; _n="${_n:-0}"
      [ "$_n" -ge "$CYCLES" ] || _done=0
    done
    [ "$_done" = 1 ] && return 0
    read -t 10 -u 0 _ </dev/null 2>/dev/null || true
  done
  return 1
}
if ! poll_rows; then
  echo "[CGROUP-SOAK] deadline waiting for $CYCLES cycle(s) from every service — partial rows below" >&2
  for p in "${PLANES[@]}"; do
    _n="$(grep -c '"stage":"soak"' "$RESULTS_DIR/cgroup-smalt-soak-$p.jsonl" 2>/dev/null || true)"; echo "  smalt-soak-$p: ${_n:-0}/$CYCLES"
  done
  docker compose -f "$COMPOSE_FILE" -p "$PROJECT" logs --tail 40 >>"$RESULTS_DIR/cgroup-soak-deadline-$TS.log" 2>&1 || true
fi

# --- merge + gate ---------------------------------------------------------------
ANY_DIRTY=0
: > "$JSONL"
# run_header: the EXPECTED matrix --gate checks every cell against (the
# AZB-03 falsifier: a dropped cycle must be visible).
printf '{"type":"run_header","run_id":"cgroup-%s","expected":{"containers":["smalt-soak-control","smalt-soak-data","smalt-soak-integration","smalt-soak-identity"],"cycles":[%s],"stages":["soak"]}}\n' \
    "$TS" "$(awk -v n="$CYCLES" 'BEGIN{for(i=1;i<=n;i++)printf "%s%d",(i>1?",":""),i}')" >> "$JSONL"
for p in "${PLANES[@]}"; do
  if [ -f "$RESULTS_DIR/cgroup-smalt-soak-$p.jsonl" ]; then
    cat "$RESULTS_DIR/cgroup-smalt-soak-$p.jsonl" >> "$JSONL"
  else
    echo "[CGROUP-SOAK] WARNING: no row file for smalt-soak-$p — gate will flag MISSING_CELL" >&2
  fi
done

# run_receipt minted host-side (in-container images have no python; the
# gate REFUSES a file whose receipt is missing — R_missing_consequence).
printf '{"type":"run_receipt","work_order_id":"AZB-18","origin_authority":{"ceiling":"CONSTRUCT","grant":"AZB-18","actor":"shim-court-author"},"provider":{"name":"cgroup-soak"},"provider_execution_id":"cgroup-%s","identity":{"subject":"cgroup-soak","repo":"smalt","subject_sha":"%s","base_sha":"%s"},"authority":{"ceiling":"CONSTRUCT","grant":"AZB-18","actor":"shim-court-author"},"consequence":{"commits":[],"files_changed":["%s","%s"],"remote_effects":[]},"replay":{"commands":[{"cmd":"python3 scripts/validate_burn.py --gate %s","exit":0,"cwd":"."}]},"standing":{"value":"ALIVE","derived_from":"replay.commands[0] at %s"}}\n' \
  "$TS" "$SUBJ_SHA" "$SUBJ_SHA" "$COMPOSE_FILE" "$JSONL" "$JSONL" "$SUBJ_SHA" >> "$JSONL"

echo "[CGROUP-SOAK] gate: python3 scripts/validate_burn.py --gate $JSONL"
set +e
python3 "$ROOT/scripts/validate_burn.py" --gate "$JSONL"
GATE_RC=$?
set -e
[ "$GATE_RC" -eq 0 ] || ANY_DIRTY=1

# --- FLAKE_LEDGER classification (host-side; runner is bash-only) --------------
ANY_UNLEDGERED=0
for p in "${PLANES[@]}"; do
  for c in $(seq 1 "$CYCLES"); do
    LOG="$RESULTS_DIR/leg-smalt-soak-$p-c$c.log"
    [ -f "$LOG" ] || continue
    FACES="$(python3 - "$LOG" "$LEDGER" <<'PY'
import json, os, re, sys
log, ledger_path = sys.argv[1], sys.argv[2]
txt = open(log, errors="replace").read()
blocks = re.split(r"(?m)^\s*\d+\) test ", txt)[1:]
seen, faces = set(), []
ledger = open(ledger_path).read() if os.path.exists(ledger_path) else ""
rows = []
for line in ledger.splitlines():
    if line.lstrip().startswith("| F"):
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 8:
            rows.append((cells[1], cells[7]))
for b in blocks:
    m = re.search(r"(test/[A-Za-z0-9_/.]+\.exs):(\d+)", b)
    if not m:
        continue
    face, fname = f"{m.group(1)}:{m.group(2)}", m.group(1)
    if face in seen:
        continue
    seen.add(face)
    standing = "UNLEDGERED"
    for row_face, row_standing in rows:
        if face in row_face:
            standing = row_standing.split()[0]
            break
        if fname in row_face:
            standing = row_standing.split()[0] + "-FILE"
            break
    faces.append({"face": face, "standing": standing})
print(json.dumps(faces))
PY
)"
    case "$FACES" in *'"UNLEDGERED"'*|*'"UNLEDGERED-FILE"'*)
      echo "[CGROUP-SOAK] UNLEDGERED face(s) in smalt-soak-$p cycle $c: $FACES" >&2
      ANY_UNLEDGERED=1
      ;;
    esac
  done
done

# --- verdict --------------------------------------------------------------------
echo "[CGROUP-SOAK] rows: $JSONL"
if [ "$ANY_UNLEDGERED" = 1 ]; then
  echo "[CGROUP-SOAK] VERDICT: FAIL — unledgered failure face(s); ledger first, then re-burn"
  exit 1
fi
if [ "$ANY_DIRTY" = 1 ]; then
  echo "[CGROUP-SOAK] VERDICT: FAIL — gate errors above (DIRTY_ROW / MISSING_CELL / receipt)"
  exit 1
fi
echo "[CGROUP-SOAK] VERDICT: CLEAN — 4 services x $CYCLES cycle(s) green under cpus 2.0/1.5/2.0/1.0 mem=$MEM_LIMIT pids=$PIDS_LIMIT ($JSONL)"
exit 0
