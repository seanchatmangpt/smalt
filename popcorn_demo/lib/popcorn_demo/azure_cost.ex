defmodule PopcornDemo.AzureCost do
  @moduledoc """
  Parametric Azure cost model: measured workload -> dollar estimate using
  ONLY fetched retail rates from `azurite-spike/rate-card.json` (Azure
  Retail Prices API, region eastus, USD; generated by
  `azurite-spike/fetch_rate_card.py`). No prices are hardcoded here — every
  dollar line cites the exact fetched meter name + retailPrice.

  Workload profile (all counts are measured workloads; missing keys = 0):

    %{
      cosmos_reads:  n,      # Cosmos point-read operations
      cosmos_writes: n,      # Cosmos write operations
      cosmos_ru_budget: r,   # provisioned RU/s reservation (default 100)
      blob_tx: n,            # blob transactions (reads)
      blob_tx_writes: n,     # blob transactions (writes)
      blob_gb: g,            # blob capacity GB-months
      sb_ops: n,             # Service Bus operations
      kv_ops: n,             # Key Vault operations
      eh_ingress_gb: g       # Event Hubs ingress volume (GB)
    }

  Optional: `hours` — reservation hours for hourly meters (default 730 =
  one cloud month).
  """

  alias PopcornDemo.AzureCost.{Line, Profile}

  @default_hours 730.0

  # Event Hubs Standard throughput unit admits 1 MB/s ingress
  # (= 3.6 GB/hour). Derived factor, documented here; the *rate* itself is
  # always the fetched one.
  @eh_gb_per_tu_hour 3.6

  @type workload :: map()

  @doc """
  Load the fetched rate card. Returns `{rates, meta}` where rates maps each
  rate key to a `%Line.Rate{}` carrying meter name, sku, unit, retailPrice
  and the family fetch timestamp.
  """
  @spec load_rates(Path.t()) :: {map(), map()}
  def load_rates(path \\ default_path()) do
    raw = File.read!(Path.expand(path))
    json = Jason.decode!(raw)

    rates =
      json["rates"]
      |> Enum.into(%{}, fn {k, r} ->
        {k,
         %Line.Rate{
           key: k,
           meter_name: r["meterName"],
           sku_name: r["skuName"],
           product_name: r["productName"],
           unit: r["unitOfMeasure"],
           retail_price: r["retailPrice"],
           fetched_at: json["_meta"]["fetched_at"]
         }}
      end)

    {rates, json["_meta"]}
  end

  @doc """
  Price a measured workload profile against the fetched rates.

  Returns `{:ok, %{lines: [Line.t()], total: float}}` where every line cites
  meter + retailPrice, or `{:error, {:missing_rates, keys}}` if the rate
  card lacks a required meter.
  """
  @spec price(workload(), map(), keyword()) ::
          {:ok, %{lines: [Line.t()], total: float}}
          | {:error, {:missing_rates, [atom()]}}
  def price(profile, rates, opts \\ []) do
    with :ok <- Profile.validate(profile),
         {:ok, plan} <- plan(Profile.normalize(profile), rates, opts) do
      total = 0.0 + (plan |> Enum.map(& &1.amount) |> Enum.sum())
      {:ok, %{lines: plan, total: total}}
    end
  end

  @doc """
  The local bill: local compute runs at $0 — the emulator's data-plane and
  messaging workloads displace an Azure bill without incurring one.
  `displacement/2` is simply `price/3` (azure_bill == displacement since the
  local workload's Azure-equivalent costs $0 to serve locally); kept as a
  named function so call sites are legible.
  """
  @spec displacement(workload(), map(), keyword()) ::
          {:ok, %{lines: [Line.t()], total: float}} | {:error, term()}
  def displacement(profile, rates, opts \\ []), do: price(profile, rates, opts)

  defp plan(p, rates, opts) do
    hours = Keyword.get(opts, :hours, @default_hours)
    eh_hours = p.eh_ingress_gb / @eh_gb_per_tu_hour

    spec =
      [
        {:cosmos_reservation, p.cosmos_reads + p.cosmos_writes,
         "cosmos_provisioned_rus", hours * p.cosmos_ru_budget / 100.0,
         "100-RU/s hour"},
        {:cosmos_burst_overage, p.cosmos_reads + p.cosmos_writes,
         "cosmos_burst_1m_rus",
         (p.cosmos_reads * 1.0 + p.cosmos_writes * 5.0) / 1_000_000.0,
         "1M RUs"},
        {:blob_read_tx, p.blob_tx, "blob_read_ops", p.blob_tx / 10_000.0,
         "10K tx"},
        {:blob_write_tx, p.blob_tx_writes, "blob_write_ops",
         p.blob_tx_writes / 10_000.0, "10K tx"},
        {:blob_capacity, p.blob_gb, "blob_stored_gb", p.blob_gb, "GB-month"},
        {:sb_base_unit, p.sb_ops, "sb_standard_base_unit", hours,
         "base-unit hour"},
        {:sb_ops, p.sb_ops, "sb_standard_ops", p.sb_ops / 1_000_000.0,
         "1M ops"},
        {:sb_premium_mus, p.sb_ops, "sb_premium_mu", hours,
         "premium MU hour"},
        {:kv_ops, p.kv_ops, "kv_ops", p.kv_ops / 10_000.0, "10K ops"},
        {:eh_ingress, p.eh_ingress_gb, "eh_standard_tu", eh_hours, "TU hour"}
      ]

    missing_rates =
      for {_key, w, rate_key, _q, _u} <- spec,
          w > 0,
          is_nil(rates[rate_key]),
          uniq: true do
        rate_key
      end

    if missing_rates != [] do
      {:error, {:missing_rates, missing_rates}}
    else
      lines =
        spec
        |> Enum.map(fn {key, weight, rate_key, qty, unit} ->
          Line.build(key, weight, rates[rate_key], qty: qty, unit: unit)
        end)
        |> Enum.reject(&(&1.weight == 0))

      {:ok, lines}
    end
  end

  defp default_path,
    do: Path.join(__DIR__, "../../azurite-spike/rate-card.json")
end
