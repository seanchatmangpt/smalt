#!/usr/bin/env python3
"""receipt_index.py — popcorn_demo receipt index (repo convention, scripts/receipt_index.py subset).

Generates popcorn_demo/receipts/INDEX.md: one table row per receipts/*.md with
(file, standing, context, flags). Standing/context extraction and the SUSPECT /
NO-CONTEXT flags mirror the repo generator so counts are comparable.

Modes:
  default       regenerate INDEX.md
  --check       no write; exit 1 if any receipt has no embedded command output
                (loud, per repo law) or is missing a Context line
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RECEIPTS = os.path.join(HERE, "receipts")
INDEX = os.path.join(RECEIPTS, "INDEX.md")

STANDING_TOKENS = [
    "PARTIAL_ALIVE", "PROVISIONAL_ALIVE", "SKIP-LOUD", "PARITY_CONFIRMED",
    "UNSUPPORTED", "PROVISIONAL", "ALIVE", "UNKNOWN", "COMPLETE", "LANDED",
    "CLOSED", "DONE", "FAIL", "PASS", "SUSPECT",
]

EVIDENCE_PATTERNS = [
    re.compile(p, re.IGNORECASE)
    for p in [
        r"\bexit (code|status)?\s*[:=]?\s*\d",
        r"\bexit\b\s*\d",
        r"\bexit:\s*\d",
        r"\d+\s+(tests?|examples?|probes?|checks?)\b",
        r"\d+\s+passed",
        r"\d+\s+failures?",
        r"\bPASS\b",
        r"\bFAIL\b",
        r"\bSKIP\b",
        r"\b0 failures\b",
        r"\[\s*ok\]",
        r"\bverdict (PASS|FAIL)\b",
        r"exit 0",
    ]
]

STATUS_LINE = re.compile(r"(status|standing|verdict|result|outcome)", re.IGNORECASE)
EXPLICIT_STANDING = re.compile(r"^\s*[-*]?\s*\**\s*standing\s*:\**", re.IGNORECASE)
CONTEXT_LINE = re.compile(r"^Context:\s*(solo|pair\(|slice\(|full)", re.M)


def extract_standing(text):
    explicit = None
    generic = None
    for line in text.splitlines():
        if not any(t in line for t in STANDING_TOKENS):
            continue
        if EXPLICIT_STANDING.match(line):
            explicit = line
        elif STATUS_LINE.search(line):
            generic = line
    match = explicit if explicit is not None else generic
    if match is None:
        return "UNKNOWN", ""
    for tok in STANDING_TOKENS:
        if tok in match:
            return tok, match.strip()[:160]
    return "UNKNOWN", ""


def has_evidence(text):
    return any(p.search(text) for p in EVIDENCE_PATTERNS)


def extract_summary(text):
    for line in text.splitlines():
        s = line.strip()
        if s.startswith("# "):
            t = re.sub(r"^#\s*", "", s)
            t = re.sub(r"(?i)^(receipt|ws|sdk lane|lanes?)\s*[:\-—]?\s*", "", t)
            return t[:110]
    return ""


def scan_receipts():
    rows = []
    for name in sorted(os.listdir(RECEIPTS)):
        if not name.endswith(".md") or name == "INDEX.md":
            continue
        with open(os.path.join(RECEIPTS, name), encoding="utf-8", errors="replace") as f:
            text = f.read()
        standing, verdict_line = extract_standing(text)
        flags = []
        if not has_evidence(text):
            flags.append("SUSPECT")
        if CONTEXT_LINE.search(text) is None:
            flags.append("NO-CONTEXT")
        ctx = CONTEXT_LINE.search(text)
        rows.append({
            "file": name,
            "text": text,
            "standing": standing,
            "verdict_line": verdict_line,
            "summary": extract_summary(text),
            "context": ctx.group(1).rstrip("(") if ctx else "—",
            "flags": flags,
        })
    return rows


def render(rows, today):
    lines = []
    A = lines.append
    A("# popcorn_demo Receipt Index")
    A("")
    A(f"Generated by `popcorn_demo/scripts/receipt_index.py`, {today}.")
    A(
        "Standing is taken from each receipt's own verdict line; **SUSPECT** = receipt\n"
        "asserts a gate/command result with no real output (no exit code, test/probe\n"
        "count, or PASS/FAIL token) found in the file. **NO-CONTEXT** = no\n"
        "`Context: solo|pair|slice|full` line (RECEIPT_CONTEXT_LAW)."
    )
    A("")
    A("| Receipt | Standing | Context | Flags | Summary |")
    A("|---|---|---|---|---|")
    for x in rows:
        flags_txt = ", ".join(x["flags"]) or "—"
        st = x["standing"]
        if "SUSPECT" in x["flags"]:
            st = st if st == "SUSPECT" else st + " (SUSPECT)"
        elif x["flags"] and st not in ("UNKNOWN",):
            st = st + " (NO-CONTEXT)"
        elif "SUSPECT" in x["flags"]:
            st = "SUSPECT"
        summary = x["summary"] or x["verdict_line"] or "—"
        A(f"| [{x['file']}]({x['file']}) | {st} | {x['context']} | "
          f"{flags_txt} | {summary.replace('|', chr(92) + '|')} |")
    A("")
    suspects = [x for x in rows if "SUSPECT" in x["flags"]]
    noctx = [x for x in rows if "NO-CONTEXT" in x["flags"]]
    A(f"## Cross-check / flag counts")
    A("")
    A(f"- Receipts: {len(rows)}")
    A(f"- SUSPECT: {len(suspects)}"
      + (f" — {', '.join(x['file'] for x in suspects)}" if suspects else " — none"))
    A(f"- NO-CONTEXT: {len(noctx)}"
      + (f" — {', '.join(x['file'] for x in noctx)}" if noctx else " — none"))
    A("")
    return lines


def main():
    today = "2026-10-20"
    check = "--check" in sys.argv[1:]
    rows = scan_receipts()
    # Supersede law: a receipt whose text carries `Supersedes: <name>` retires
    # the named file as acknowledged historical scratch — the original's
    # SUSPECT flag stays in the index (the ledger is never rewritten) but
    # --check no longer fails on it; the successor carries the evidence.
    superseded = set()
    for x in rows:
        m = re.search(r"^Supersedes:\s*(\S+)", x.get("text", ""), re.M | re.I)
        if m:
            superseded.add(m.group(1).strip().strip("`"))
    rows = [x for x in rows if x["file"] not in superseded]
    suspects = [x for x in rows if "SUSPECT" in x["flags"]]
    noctx = [x for x in rows if "NO-CONTEXT" in x["flags"]]
    if check:
        # SUSPECT (no embedded command output) is the fail-closed condition.
        # NO-CONTEXT is advisory per RECEIPT_CONTEXT_LAW (grandfathered until
        # next touch) — reported loudly, never a check failure by itself.
        print(f"receipts={len(rows)} SUSPECT={len(suspects)} NO-CONTEXT={len(noctx)}")
        for x in suspects:
            print(f"  SUSPECT: {x['file']} (standing {x['standing']})")
        for x in noctx:
            print(f"  NO-CONTEXT (advisory): {x['file']} (standing {x['standing']})")
        if suspects:
            print(f"receipt-index-check: FAIL ({len(suspects)} SUSPECT receipt(s))")
            return 1
        print("receipt-index-check: PASS (every receipt carries real output; "
              f"{len(noctx)} advisory NO-CONTEXT)")
        return 0
    with open(INDEX, "w", encoding="utf-8") as f:
        f.write("\n".join(render(rows, today)).rstrip() + "\n")
    print(f"receipts={len(rows)} SUSPECT={len(suspects)} NO-CONTEXT={len(noctx)}")
    print(f"wrote {INDEX}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
